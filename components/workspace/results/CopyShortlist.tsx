"use client";

import { useEffect, useRef, useState } from "react";
import { AnimatePresence, motion } from "motion/react";
import { Copy } from "lucide-react";
import { Badge, Button } from "@/components/ui";
import { formatPhase, formatStatus, tierLabel } from "@/lib/ctgov/format";
import { rankTrials, useShortlistedCount, useWorkspace, type WorkspaceState } from "../store";
import { patientDisplay } from "../labels";

/** Plain-text export of the shortlisted trials. */
export function buildShortlistText(state: WorkspaceState): string {
  const { profile, patientLabel, trials, matches, matchStatus, reviews, trace } = state;
  const patient = patientDisplay(profile, patientLabel);
  const ranked = rankTrials(trials, matches, matchStatus, reviews).filter((e) => e.review === "shortlisted" && e.match);
  const reviewed = Object.keys(matches).length;
  const strong = Object.values(matches).filter((m) => m.tier === "strong").length;
  const possible = Object.values(matches).filter((m) => m.tier === "possible").length;

  const lines: string[] = [];
  lines.push(`Trial shortlist — ${patient.label}${patient.ageSex ? ` (${patient.ageSex})` : ""}`);
  lines.push(
    `${trace ? `${trace.harvested.toLocaleString("en-US")} studies harvested · ` : ""}${reviewed} reviewed criterion by criterion · ${strong} strong · ${possible} possible · ${ranked.length} shortlisted`,
  );
  lines.push("");

  ranked.forEach((e, i) => {
    const m = e.match!;
    const textById = new Map(e.trial.criteria.map((c) => [c.id, c.text]));
    const actionById = new Map(m.verdicts.map((v) => [v.criterionId, v.actionNeeded]));
    const short = (id: string) => {
      const t = textById.get(id) ?? id;
      return t.length > 140 ? `${t.slice(0, 137).trimEnd()}…` : t;
    };
    lines.push(`${i + 1}. ${e.trial.nctId} — ${e.trial.title}`);
    lines.push(`   ${tierLabel(m.tier)} · score ${m.score}/100 · ${formatPhase(e.trial.phases)} · ${formatStatus(e.trial.status)}`);
    lines.push(`   ${m.headline}`);
    lines.push(m.blockers.length > 0 ? `   Blockers: ${m.blockers.map(short).join("; ")}` : "   Blockers: none");
    if (m.confirmations.length > 0) {
      lines.push(`   To confirm: ${m.confirmations.map((id) => actionById.get(id) ?? short(id)).join("; ")}`);
    }
    lines.push(`   ${e.trial.url}`);
    lines.push("");
  });

  lines.push("Generated by Trial Matcher (prototype). Verdicts require clinician review.");
  return lines.join("\n");
}

async function copyText(text: string): Promise<void> {
  try {
    await navigator.clipboard.writeText(text);
  } catch {
    const el = document.createElement("textarea");
    el.value = text;
    el.setAttribute("readonly", "");
    el.style.position = "fixed";
    el.style.opacity = "0";
    document.body.appendChild(el);
    el.select();
    document.execCommand("copy");
    document.body.removeChild(el);
  }
}

export function CopyShortlist() {
  const shortlisted = useShortlistedCount();
  const [copied, setCopied] = useState(false);
  const timer = useRef<number | undefined>(undefined);

  useEffect(() => () => window.clearTimeout(timer.current), []);

  const onCopy = async () => {
    await copyText(buildShortlistText(useWorkspace.getState()));
    setCopied(true);
    window.clearTimeout(timer.current);
    timer.current = window.setTimeout(() => setCopied(false), 1800);
  };

  return (
    <span className="inline-flex items-center gap-2">
      <AnimatePresence>
        {copied && (
          <motion.span
            initial={{ opacity: 0, y: 4 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: -4 }}
            transition={{ duration: 0.18, ease: "easeOut" }}
            role="status"
          >
            <Badge tone="accent" dot>
              Copied
            </Badge>
          </motion.span>
        )}
      </AnimatePresence>
      <Button
        variant="secondary"
        size="sm"
        icon={<Copy />}
        onClick={() => void onCopy()}
        disabled={shortlisted === 0}
        title={shortlisted === 0 ? "Shortlist a trial first" : "Copy the shortlist as plain text"}
      >
        Copy shortlist{shortlisted > 0 ? ` (${shortlisted})` : ""}
      </Button>
    </span>
  );
}
